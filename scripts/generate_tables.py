#!/usr/bin/env python3
"""Original, procedurally generated, band-limited waveform tables. No Shrub assets."""
from pathlib import Path
import math
N = 256
LIMITS = [96,64,48,32,24,16,8,4,1]
N_WAVES, N_FRAMES = 4,4
out = Path(__file__).resolve().parents[1] / 'src' / 'tables.h'
with out.open('w') as f:
    f.write('/* GENERATED by scripts/generate_tables.py. Independently synthesized data. */\n')
    f.write('#ifndef SPRIG_TABLES_H\n#define SPRIG_TABLES_H\n')
    f.write('#define SPRIG_WAVES 4\n#define SPRIG_FRAMES 4\n#define SPRIG_BANDS 9\n#define SPRIG_TABLE_LEN 256\n')
    f.write('static const unsigned short sprig_harmonic_limits[9] = {'+', '.join(str(h) for h in LIMITS)+'};\n')
    f.write('static const float sprig_wavetables[4][4][9][256] = {\n')
    for w in range(N_WAVES):
        f.write('{\n')
        for frame in range(N_FRAMES):
            f.write('{\n')
            for lim in LIMITS:
                a=[]
                for j in range(N):
                    phase=2*math.pi*j/N
                    value=0.0
                    if w==0:  # progressively harmonic sine-derived timbres
                        value=math.sin(phase)
                        if frame:
                            value+= (0.12*frame)*math.sin(2*phase+0.2*frame) if lim>=2 else 0
                            value+= (0.07*frame)*math.sin(3*phase) if lim>=3 else 0
                    elif w==1:  # saw with varying harmonic tilt
                        tilt=[2.5,1.8,1.3,1.0][frame]
                        for n in range(1,lim+1):
                            value+= ((1 if n%2 else -1) / n**tilt)*math.sin(n*phase)
                    elif w==2:  # pulse family varying pulse widths
                        duty=[0.5,0.42,0.33,0.24][frame]
                        for n in range(1,lim+1):
                            value+=(math.sin(math.pi*n*duty)/n)*math.cos(n*phase)
                    else: # triangle family, varying odd-harmonic strength
                        tilt=[4.0,2.5,2.0,1.6][frame]
                        for n in range(1,lim+1,2):
                            value+=(-1 if (n-1)//2%2 else 1)*math.sin(n*phase)/(n**tilt)
                    a.append(value)
                peak=max(abs(x) for x in a) or 1
                a=[0.87*x/peak for x in a]
                f.write('{'+','.join(f'{v:.7f}f' for v in a)+'},\n')
            f.write('},\n')
        f.write('},\n')
    f.write('};\n')
    f.write('static const float sprig_note_phase_inc[128] = {\n')
    for n in range(128):
        hz=440.0*2.0**((n-69)/12.0)
        f.write(f'{(hz*N/44100):.9f}f,')
        if n%8==7:f.write('\n')
    f.write('};\n')
    f.write('static const unsigned char sprig_note_band[128] = {\n')
    for n in range(128):
        hz=440.0*2.0**((n-69)/12.0)
        allowed = max(1,int(19000.0/hz))
        band=next((i for i,x in enumerate(LIMITS) if x<=allowed),8)
        f.write(f'{band},')
        if n%16==15:f.write('\n')
    f.write('};\n')
    f.write('static const float sprig_cutoff_g[101] = {\n')
    for i in range(101):
        hz=35* (15000/35)**(i/100)
        g=math.tan(math.pi*hz/44100)
        f.write(f'{g:.9f}f,')
        if i%8==7:f.write('\n')
    f.write('};\n#endif\n')
print(f'{out}: {out.stat().st_size} bytes')
